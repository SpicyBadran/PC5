#!/usr/bin/env python3
"""PC5 milestone graph: validate, render and keep the document in sync.

The architecture makes one promise that is easy to lose by accident: **the
destination is genuine PS5 system software running on PC hardware, and every
milestone serves it.** The previous version of this tool enforced the opposite
promise ("the PS5 work may never gate the product"), which made the destination
structurally optional. This version enforces the real one:

  * the product identity, mission, foundation role, non-goals and success levels
    live in `docs/architecture/roadmap.json` and are validated as data;
  * the destination milestone exists, is level 5, is reachable from the roots,
    and may never be `complete` without evidence;
  * every required milestone exists, so the destination cannot be deleted by
    tidying up;
  * no `experimental` milestone may gate a `release_gating` milestone of kind
    `infrastructure` or `native-platform` (release isolation, ADR-021);
  * every milestone names its workstream, kind, level, acceptance criteria and
    the mission link (`advances`) it serves;
  * `complete` requires evidence, every evidence path exists, `blocked` names its
    blocker, `superseded_by` names real milestones;
  * the generated block in the graph document matches the data exactly.

Usage:
    python3 tools/roadmap.py check
    python3 tools/roadmap.py render
    python3 tools/roadmap.py sync
    python3 tools/roadmap.py path        # the destination path, one line

Exit codes: 0 = clean, 1 = validation or sync error, 2 = usage/environment.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_GRAPH = os.path.join(ROOT, "docs", "architecture", "roadmap.json")
DEFAULT_DOC = os.path.join(ROOT, "docs", "architecture", "PC5_MILESTONE_GRAPH.md")

SCHEMA = "pc5.roadmap/2"
STATES = ("complete", "in_progress", "blocked", "not_started")
KINDS = (
    "governance",
    "infrastructure",
    "native-platform",
    "ps5-compatibility",
    "research",
    "hardware-validation",
    "product-experience",
)
RELEASE_KINDS = ("infrastructure", "native-platform", "governance")
ID_RE = re.compile(r"^M[0-9]+[a-z]?$")
WS_RE = re.compile(r"^WS[0-9]+$")
ADR_RE = re.compile(r"^ADR-[0-9]{3}$")
BEGIN = "<!-- roadmap:begin generated by tools/roadmap.py render — do not edit by hand -->"
END = "<!-- roadmap:end -->"


class GraphError(Exception):
    """The graph file could not be loaded or is not even the right shape."""


# --------------------------------------------------------------------- load


def load(path=DEFAULT_GRAPH):
    try:
        with open(path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
    except FileNotFoundError:
        raise GraphError(f"roadmap graph not found: {path}")
    except json.JSONDecodeError as exc:
        raise GraphError(f"{path}: invalid JSON: {exc}")
    if not isinstance(data, dict):
        raise GraphError(f"{path}: top-level value must be an object")
    return data


def milestones(data):
    out = data.get("milestones", [])
    return out if isinstance(out, list) else []


def by_id(data):
    return {m["id"]: m for m in milestones(data) if isinstance(m, dict) and "id" in m}


# ----------------------------------------------------------------- validate


def _is_str_list(value, allow_empty=False):
    if not isinstance(value, list):
        return False
    if not value:
        return allow_empty
    return all(isinstance(v, str) and v.strip() for v in value)


def _sort_key(mid):
    match = re.match(r"^M([0-9]+)([a-z]?)$", mid)
    return (int(match.group(1)), match.group(2)) if match else (10**6, mid)


def _closure(start, nodes):
    """Every milestone reachable from `start` following depends_on."""
    seen, stack = set(), [start]
    while stack:
        current = stack.pop()
        for dep in nodes.get(current, {}).get("depends_on", []):
            if dep not in seen:
                seen.add(dep)
                stack.append(dep)
    return seen


def _validate_product(product, levels_by_id, errors):
    if not isinstance(product, dict):
        errors.append("product must be an object")
        return {}
    for field in ("name", "identity", "mission"):
        if not isinstance(product.get(field), str) or not product.get(field, "").strip():
            errors.append(f"product.{field} must be a non-empty string")

    identity = " ".join(str(product.get(field, "")) for field in ("identity", "mission")).lower()
    if "linux distribution" in identity or "playstation-themed" in identity:
        errors.append(
            "product.identity/mission describes a Linux distribution rather than a PlayStation 5 "
            "platform; the destination is the genuine PS5 system software (ADR-019)")

    dest = product.get("destination")
    if not isinstance(dest, dict):
        errors.append("product.destination must be an object")
        dest = {}
    for field in ("statement", "milestone", "evidence_class"):
        if not isinstance(dest.get(field), str) or not dest.get(field, "").strip():
            errors.append(f"product.destination.{field} must be a non-empty string")
    if not isinstance(dest.get("level"), int) or dest.get("level") not in levels_by_id:
        errors.append("product.destination.level must be a declared success level")
    if not _is_str_list(dest.get("must_not_be_satisfied_by")):
        errors.append("product.destination.must_not_be_satisfied_by must state what the destination is not")

    foundation = product.get("foundation")
    if not isinstance(foundation, dict):
        errors.append("product.foundation must be an object naming the substrate and its role")
    else:
        role = foundation.get("role")
        if not isinstance(role, str) or not role.strip():
            errors.append("product.foundation.role must be a non-empty string")
        if not isinstance(foundation.get("product_surface"), str) or not foundation.get("product_surface", "").strip():
            errors.append("product.foundation.product_surface must name what the product actually is")
        if not isinstance(foundation.get("adr"), str) or not ADR_RE.match(foundation.get("adr", "")):
            errors.append("product.foundation.adr must be an ADR id")
        if foundation.get("role") in ("product", "destination", "final-product"):
            errors.append(
                "product.foundation.role must not make the foundation the product; "
                "the substrate is hardware enablement (ADR-020)")
        if foundation.get("required_for_product") is not False:
            errors.append("product.foundation.required_for_product must be false: a release must build without it")

    if not _is_str_list(product.get("non_goals")):
        errors.append("product.non_goals must be a non-empty list")

    claims = product.get("forbidden_claims")
    if not _is_str_list(product.get("required_milestones")):
        errors.append("product.required_milestones must be a non-empty list of milestone ids")
    if not isinstance(claims, list) or not claims:
        errors.append("product.forbidden_claims must be a non-empty list")
        return product
    for index, claim in enumerate(claims):
        where = f"product.forbidden_claims[{index}]"
        if not isinstance(claim, dict):
            errors.append(f"{where}: must be an object")
            continue
        if not isinstance(claim.get("pattern"), str) or not claim["pattern"].strip():
            errors.append(f"{where}: pattern must be a non-empty string")
        if not isinstance(claim.get("why"), str) or not claim["why"].strip():
            errors.append(f"{where}: why must say what the claim would do to the architecture")
        if not _is_str_list(claim.get("allowed_in"), allow_empty=True):
            errors.append(f"{where}: allowed_in must be a list of relative paths")
    return product


def validate(data, root=ROOT):
    """Return a list of human-readable error strings (empty means valid)."""
    errors = []

    if data.get("schema") != SCHEMA:
        errors.append(f"schema must be {SCHEMA!r}, found {data.get('schema')!r}")
    if "version" in data:
        # Two documents used to publish a "version", and readers could not tell
        # the roadmap document's revision from the product's.  The product
        # version lives in `Makefile VERSION`; the roadmap keeps only the
        # revision of this document, under a name that says so.
        errors.append("roadmap must use 'document_version'; the product version "
                      "lives in Makefile VERSION")
    for field in ("document_version", "product_version_source", "updated", "authority"):
        if not isinstance(data.get(field), str) or not data.get(field, "").strip():
            errors.append(f"{field} must be a non-empty string")
    # --- foundations -------------------------------------------------------
    # Delivered work that earns no milestone credit.  A foundation names the
    # milestone it serves, states what it does *not* complete, and points at
    # evidence that exists; it can never mark a milestone complete.
    foundations = data.get("foundations", [])
    if not isinstance(foundations, list):
        errors.append("foundations must be a list")
        foundations = []
    seen_foundations = set()
    for index, foundation in enumerate(foundations):
        where = f"foundations[{index}]"
        if not isinstance(foundation, dict):
            errors.append(f"{where}: must be an object")
            continue
        for field in ("id", "title", "milestone", "state"):
            if not isinstance(foundation.get(field), str) or not foundation.get(field, "").strip():
                errors.append(f"{where}: {field} must be a non-empty string")
        if foundation.get("id") in seen_foundations:
            errors.append(f"{where}: duplicate id {foundation.get('id')!r}")
        seen_foundations.add(foundation.get("id"))
        for field in ("delivers", "does_not_complete"):
            values = foundation.get(field)
            if not isinstance(values, list) or not values or \
                    not all(isinstance(item, str) and item.strip() for item in values):
                errors.append(f"{where}: {field} must be a non-empty list of strings")
        if not isinstance(foundation.get("does_not_complete"), list) or \
                not foundation.get("does_not_complete"):
            errors.append(f"{where}: a foundation must say what it does not complete")
        for path in foundation.get("evidence", []) or []:
            if not isinstance(path, str) or not os.path.exists(os.path.join(root, path)):
                errors.append(f"{where}: evidence does not exist: {path}")

    authority = data.get("authority")
    if isinstance(authority, str) and authority and not os.path.exists(os.path.join(root, authority)):
        errors.append(f"authority document does not exist: {authority}")

    # --- success levels -----------------------------------------------------
    levels = data.get("product", {}).get("levels") if isinstance(data.get("product"), dict) else None
    levels_by_id = {}
    if not isinstance(levels, list) or len(levels) < 2:
        errors.append("product.levels must define the success hierarchy")
        levels = []
    for index, level in enumerate(levels):
        where = f"product.levels[{index}]"
        if not isinstance(level, dict):
            errors.append(f"{where}: must be an object")
            continue
        if not isinstance(level.get("level"), int):
            errors.append(f"{where}: level must be an integer")
            continue
        if level["level"] in levels_by_id:
            errors.append(f"{where}: duplicate level {level['level']}")
        levels_by_id[level["level"]] = level
        for field in ("statement", "acceptance", "evidence_class"):
            if not isinstance(level.get(field), str) or not level.get(field, "").strip():
                errors.append(f"{where}: {field} must state the acceptance criteria")
    if levels_by_id and sorted(levels_by_id) != list(range(1, len(levels_by_id) + 1)):
        errors.append("product.levels must be numbered 1..N without gaps")

    product = _validate_product(data.get("product"), levels_by_id, errors)

    # --- workstreams --------------------------------------------------------
    workstreams = data.get("workstreams")
    ws_ids = set()
    if not isinstance(workstreams, list) or not workstreams:
        errors.append("workstreams must be a non-empty list")
        workstreams = []
    for index, ws in enumerate(workstreams):
        where = f"workstreams[{index}]"
        if not isinstance(ws, dict):
            errors.append(f"{where}: must be an object")
            continue
        wid = ws.get("id")
        if not isinstance(wid, str) or not WS_RE.match(wid):
            errors.append(f"{where}: id must look like WS<number>, found {wid!r}")
            continue
        if wid in ws_ids:
            errors.append(f"{where}: duplicate id {wid}")
        ws_ids.add(wid)
        for field in ("name", "purpose", "serves_level"):
            if not isinstance(ws.get(field), str) or not ws.get(field, "").strip():
                errors.append(f"workstream {wid}: {field} must be a non-empty string")
    if ws_ids and ws_ids != {f"WS{i}" for i in range(len(ws_ids))}:
        errors.append("workstreams must be numbered WS0..WSn without gaps")

    roles = data.get("roles")
    if not _is_str_list(roles):
        errors.append("roles must be a non-empty list of strings")
        roles = []
    elif len(set(roles)) != len(roles):
        errors.append("roles contains duplicates")

    if errors:
        # The structure is too broken for the rest of the checks to mean anything.
        return errors

    # --- milestones ---------------------------------------------------------
    items = milestones(data)
    if not items:
        errors.append("milestones must be a non-empty list")
        return errors

    nodes = {}
    for index, m in enumerate(items):
        where = f"milestones[{index}]"
        if not isinstance(m, dict):
            errors.append(f"{where}: must be an object")
            continue
        mid = m.get("id")
        if not isinstance(mid, str) or not ID_RE.match(mid):
            errors.append(f"{where}: id must match M<number>[a-z], found {mid!r}")
            continue
        where = f"milestone {mid}"
        if mid in nodes:
            errors.append(f"{where}: duplicate id")
            continue
        nodes[mid] = m

        if m.get("workstream") not in ws_ids:
            errors.append(f"{where}: unknown workstream {m.get('workstream')!r}")
        if m.get("kind") not in KINDS:
            errors.append(f"{where}: kind must be one of {', '.join(KINDS)}; found {m.get('kind')!r}")
        if not isinstance(m.get("level"), int) or m.get("level") not in levels_by_id:
            errors.append(f"{where}: level must be a declared success level")
        if m.get("state") not in STATES:
            errors.append(f"{where}: state must be one of {', '.join(STATES)}; found {m.get('state')!r}")
        if m.get("owner_role") not in roles:
            errors.append(f"{where}: owner_role {m.get('owner_role')!r} is not in roles")
        if not isinstance(m.get("title"), str) or not m.get("title", "").strip():
            errors.append(f"{where}: title must be a non-empty string")
        if not isinstance(m.get("advances"), str) or not m.get("advances", "").strip():
            errors.append(f"{where}: advances must say which part of the mission this milestone serves")

        deps = m.get("depends_on", [])
        if not isinstance(deps, list) or not all(isinstance(d, str) for d in deps):
            errors.append(f"{where}: depends_on must be a list of milestone ids")
            deps = []
        if len(set(deps)) != len(deps):
            errors.append(f"{where}: depends_on contains duplicates")
        if mid in deps:
            errors.append(f"{where}: depends on itself")

        for field in ("deliverables", "acceptance"):
            if not _is_str_list(m.get(field)):
                errors.append(f"{where}: {field} must be a non-empty list of non-empty strings")

        evidence = m.get("evidence", [])
        if not isinstance(evidence, list) or not all(isinstance(e, str) for e in evidence):
            errors.append(f"{where}: evidence must be a list of repository paths")
            evidence = []
        for path in evidence:
            if not os.path.exists(os.path.join(root, path)):
                errors.append(f"{where}: evidence path does not exist: {path}")

        if m.get("state") == "complete" and not evidence:
            errors.append(f"{where}: state is complete but no evidence is cited")
        if m.get("state") == "blocked":
            blocker = m.get("blocker")
            if not isinstance(blocker, str) or not blocker.strip():
                errors.append(f"{where}: state is blocked but no blocker is named")
        if "experimental" in m and not isinstance(m["experimental"], bool):
            errors.append(f"{where}: experimental must be a boolean")
        if "release_gating" in m and not isinstance(m["release_gating"], bool):
            errors.append(f"{where}: release_gating must be a boolean")
        if m.get("legacy") is not None and not _is_str_list(m.get("legacy")):
            errors.append(f"{where}: legacy must be a list of strings when present")
        if m.get("superseded_by") is not None and not _is_str_list(m.get("superseded_by")):
            errors.append(f"{where}: superseded_by must be a list of milestone ids when present")

    # Dangling dependencies after every id is known.
    for mid, m in nodes.items():
        for dep in m.get("depends_on", []) or []:
            if dep not in nodes:
                errors.append(f"milestone {mid}: depends on unknown milestone {dep!r}")
        for dep in m.get("superseded_by", []) or []:
            if dep not in nodes:
                errors.append(f"milestone {mid}: superseded_by names unknown milestone {dep!r}")
            if dep == mid:
                errors.append(f"milestone {mid}: cannot supersede itself")

    # Cycles (Kahn).
    indegree = {mid: 0 for mid in nodes}
    for mid, m in nodes.items():
        for dep in m.get("depends_on", []) or []:
            if dep in nodes:
                indegree[mid] += 1
    ready = [mid for mid, deg in indegree.items() if deg == 0]
    seen = 0
    while ready:
        current = ready.pop()
        seen += 1
        for mid, m in nodes.items():
            if current in (m.get("depends_on") or []):
                indegree[mid] -= 1
                if indegree[mid] == 0:
                    ready.append(mid)
    if seen != len(nodes):
        stuck = sorted((mid for mid, deg in indegree.items() if deg > 0), key=_sort_key)
        errors.append(f"dependency cycle among: {', '.join(stuck)}")
        return errors

    # --- the destination ----------------------------------------------------
    dest = product.get("destination") if isinstance(product, dict) else None
    dest_id = dest.get("milestone") if isinstance(dest, dict) else None
    if dest_id not in nodes:
        errors.append(f"product.destination.milestone {dest_id!r} does not exist in the graph")
    else:
        target = nodes[dest_id]
        if target.get("level") != dest.get("level"):
            errors.append(
                f"destination milestone {dest_id} is level {target.get('level')} but the product "
                f"destination is declared level {dest.get('level')}")
        if target.get("state") == "complete" and not target.get("evidence"):
            errors.append(f"destination milestone {dest_id} is complete without evidence")
        ancestors = _closure(dest_id, nodes)
        if not any(not nodes[a].get("depends_on") for a in ancestors):
            errors.append(
                f"destination milestone {dest_id} is not reachable from the graph roots: "
                f"nothing in its dependency closure is a root")

    owners = {m.get("workstream") for m in nodes.values()}
    for wid in sorted(ws_ids):
        if wid not in owners:
            errors.append(
                f"workstream {wid} has no milestone: a workstream required by the architecture "
                f"may not exist as a heading alone")

    required = product.get("required_milestones") if isinstance(product, dict) else []
    for mid in required or []:
        if mid not in nodes:
            errors.append(
                f"required milestone {mid!r} is missing: the destination workstream may not be "
                f"removed from the graph")

    # --- foundation ---------------------------------------------------------
    foundation = product.get("foundation") if isinstance(product, dict) else None
    if isinstance(foundation, dict):
        adr = foundation.get("adr")
        adr_path = os.path.join(root, "docs", "TECHNICAL_DECISIONS.md")
        if isinstance(adr, str) and os.path.exists(adr_path):
            with open(adr_path, "r", encoding="utf-8") as fh:
                decisions = fh.read()
            if f"## {adr} " not in decisions:
                errors.append(f"product.foundation.adr {adr} is not recorded in docs/TECHNICAL_DECISIONS.md")
        exit_milestone = foundation.get("exit_milestone")
        if exit_milestone is not None and exit_milestone not in nodes:
            errors.append(f"product.foundation.exit_milestone {exit_milestone!r} is not a milestone")

    # --- release isolation (ADR-021) ---------------------------------------
    # An experimental milestone depending on release milestones is normal; what
    # must not happen is the reverse, so the rule is checked from the release
    # side, once each.
    for mid, m in nodes.items():
        if not (m.get("release_gating") and m.get("kind") in RELEASE_KINDS):
            continue
        for dep in sorted(_closure(mid, nodes), key=_sort_key):
            if dep in nodes and nodes[dep].get("experimental"):
                errors.append(
                    f"release isolation violated: release-gating milestone {mid} depends on "
                    f"experimental milestone {dep} (ADR-021)")

    return errors


# -------------------------------------------------------------------- queries


def roots(data):
    return [m for m in milestones(data) if not m.get("depends_on")]


def destination_id(data):
    product = data.get("product") or {}
    dest = product.get("destination") or {}
    return dest.get("milestone")


def _longest_to(target, nodes, cache=None, stack=()):
    """Longest dependency chain ending at `target` (deterministic tie-break)."""
    cache = {} if cache is None else cache
    if target in cache:
        return cache[target]
    if target in stack or target not in nodes:
        return ([], 0)
    deps = [d for d in nodes[target].get("depends_on", []) if d in nodes]
    if not deps:
        cache[target] = ([target], 1)
        return cache[target]
    candidates = []
    for dep in deps:
        path, length = _longest_to(dep, nodes, cache, stack + (target,))
        if path:
            candidates.append((path + [target], length + 1))
    candidates.sort(key=lambda item: (-item[1], item[0]))
    cache[target] = candidates[0] if candidates else ([target], 1)
    return cache[target]


def destination_path(data):
    nodes = by_id(data)
    target = destination_id(data)
    if target not in nodes:
        return []
    return _longest_to(target, nodes, {})[0]


def critical_path(data):
    """Longest chain in the whole graph (kept for tooling that wants it)."""
    nodes = by_id(data)
    best = ([], 0)
    for mid in sorted(nodes, key=_sort_key):
        path, length = _longest_to(mid, nodes, {})
        if length > best[1] or (length == best[1] and path and best[0] and path < best[0]):
            best = (path, length)
    return best[0]


# --------------------------------------------------------------------- render


def render(data):
    product = data.get("product") or {}
    dest = product.get("destination") or {}
    ws_names = {ws["id"]: ws["name"] for ws in data.get("workstreams", [])}
    lines = [
        f"PC5 MILESTONE GRAPH  version {data.get('version', '?')}  schema {data.get('schema', '?')}  "
        f"updated {data.get('updated', '?')}",
        "",
        f"product     {product.get('name', '?')} - {product.get('identity', '?')}",
        f"destination {dest.get('milestone', '?')} (level {dest.get('level', '?')}): {dest.get('statement', '?')}",
        f"foundation  {((product.get('foundation') or {}).get('name'))} - role "
        f"{(product.get('foundation') or {}).get('role')}, not required for the product "
        f"({(product.get('foundation') or {}).get('adr')})",
        "",
    ]

    nodes = by_id(data)
    for ws in data.get("workstreams", []):
        members = sorted(
            (m for m in milestones(data) if m.get("workstream") == ws.get("id")),
            key=lambda m: _sort_key(m.get("id", "")),
        )
        lines.append(f"{ws.get('id')} - {ws.get('name')}  (serves level {ws.get('serves_level')})")
        if not members:
            lines.append("  (no milestones yet)")
        for m in members:
            deps = m.get("depends_on") or []
            dep_text = ", ".join(sorted(deps, key=_sort_key)) if deps else "-"
            flags = []
            if m.get("experimental"):
                flags.append("experimental")
            if m.get("release_gating"):
                flags.append("release-gating")
            flag_text = f"  [{', '.join(flags)}]" if flags else ""
            lines.append(
                f"  {m['id']:<5} {m['state']:<12} L{m.get('level')} {m.get('kind'):<19} "
                f"{m.get('title', '')}{flag_text}")
            lines.append(f"        depends on  {dep_text}")
        lines.append("")

    path = destination_path(data)
    lines.append("DESTINATION PATH (the critical path of the product):")
    lines.append("  " + (" -> ".join(path) if path else "(none)"))
    blocked = sorted(
        (m["id"] for m in milestones(data) if m.get("state") == "blocked"),
        key=_sort_key,
    )
    lines.append("blocked milestones: " + (", ".join(blocked) if blocked else "(none)"))
    counts = {}
    for m in milestones(data):
        counts[m.get("state")] = counts.get(m.get("state"), 0) + 1
    lines.append(
        "totals: " + ", ".join(f"{state} {counts.get(state, 0)}" for state in STATES)
        + f"  ({len(milestones(data))} milestones)"
    )
    return "\n".join(lines) + "\n"


def sync_doc(doc_path=DEFAULT_DOC, rendered=None, data=None):
    """Replace the generated block. Returns True when the file changed."""
    if rendered is None:
        rendered = render(data if data is not None else load())
    with open(doc_path, "r", encoding="utf-8") as fh:
        text = fh.read()
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < 0 or end < start:
        raise GraphError(f"{doc_path}: generated block markers not found")
    block = f"{BEGIN}\n```\n{rendered.rstrip()}\n```\n{END}"
    updated = text[:start] + block + text[end + len(END):]
    if updated == text:
        return False
    with open(doc_path, "w", encoding="utf-8") as fh:
        fh.write(updated)
    return True


def doc_block(doc_path=DEFAULT_DOC):
    with open(doc_path, "r", encoding="utf-8") as fh:
        text = fh.read()
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < 0:
        raise GraphError(f"{doc_path}: generated block markers not found")
    body = text[start + len(BEGIN):end]
    lines = body.splitlines()
    while lines and not lines[0].strip():
        lines.pop(0)
    if lines and lines[0].strip() == "```":
        lines.pop(0)
    while lines and lines[-1].strip() in ("", "```"):
        lines.pop()
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------------ cli


def main(argv=None):
    parser = argparse.ArgumentParser(description="Validate and render the PC5 milestone graph.")
    parser.add_argument("command", choices=("check", "render", "sync", "path"))
    parser.add_argument("--graph", default=DEFAULT_GRAPH)
    parser.add_argument("--doc", default=DEFAULT_DOC)
    args = parser.parse_args(argv)

    try:
        data = load(args.graph)
        errors = validate(data)
        if errors:
            for error in errors:
                print(f"roadmap: ERROR {error}", file=sys.stderr)
            print(f"roadmap: {len(errors)} error(s)", file=sys.stderr)
            return 1

        if args.command == "check":
            if not os.path.exists(args.doc):
                print(f"roadmap: ERROR document not found: {args.doc}", file=sys.stderr)
                return 1
            if doc_block(args.doc) != render(data):
                print(
                    "roadmap: ERROR generated block is out of date "
                    "(run: python3 tools/roadmap.py sync)",
                    file=sys.stderr,
                )
                return 1
            product = data.get("product") or {}
            print(
                f"roadmap: OK - {len(milestones(data))} milestones in "
                f"{len(data.get('workstreams', []))} workstreams, destination "
                f"{(product.get('destination') or {}).get('milestone')} reachable, document in sync"
            )
            return 0

        if args.command == "render":
            sys.stdout.write(render(data))
            return 0

        if args.command == "path":
            print(" -> ".join(destination_path(data)))
            return 0

        changed = sync_doc(args.doc, render(data), data)
        print(f"roadmap: {'updated' if changed else 'already current'} {args.doc}")
        return 0
    except GraphError as exc:
        print(f"roadmap: ERROR {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())

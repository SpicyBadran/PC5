#!/usr/bin/env python3
"""PC5 roadmap graph: validate, render and keep the document in sync.

The PC5 dual-track architecture makes one promise that is easy to break by
accident: **Track B must never gate Track A**.  Prose cannot enforce that, so the
milestone graph lives in `docs/architecture/roadmap.json` and this tool checks it
mechanically:

  * unique, well-formed milestone ids and known tracks/roles;
  * no dangling dependencies, no cycles;
  * a Track A milestone may not depend on a Track B milestone, directly or
    transitively (this is the gate, enforced in `validate()`);
  * every milestone has deliverables and acceptance criteria, so "done" can
    never mean "documented";
  * a `complete` milestone has evidence, every evidence path exists in the tree,
    and a `blocked` milestone names its blocker;
  * the generated block in `M0_M8_DEPENDENCY_GRAPH.md` matches the data exactly,
    so the graph cannot drift from the JSON.

Usage:
    python3 tools/roadmap.py check
    python3 tools/roadmap.py render
    python3 tools/roadmap.py sync        # rewrite the generated block
    python3 tools/roadmap.py path        # print only the Track A critical path

Exit codes: 0 = clean, 1 = validation or sync error, 2 = usage/environment.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_GRAPH = os.path.join(ROOT, "docs", "architecture", "roadmap.json")
DEFAULT_DOC = os.path.join(ROOT, "docs", "architecture", "M0_M8_DEPENDENCY_GRAPH.md")

SCHEMA = "pc5.roadmap/1"
STATES = ("complete", "in_progress", "blocked", "not_started")
ID_RE = re.compile(r"^M[0-9]+[a-z]?$")
BEGIN = "<!-- roadmap:begin generated by tools/roadmap.py render — do not edit by hand -->"
END = "<!-- roadmap:end -->"


class GraphError(Exception):
    """The graph file could not be loaded or is not even the right shape."""


# --------------------------------------------------------------------- load


def load(path=DEFAULT_GRAPH):
    try:
        with open(path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
    except FileNotFoundError:
        raise GraphError(f"roadmap graph not found: {path}")
    except json.JSONDecodeError as exc:
        raise GraphError(f"{path}: invalid JSON: {exc}")
    if not isinstance(data, dict):
        raise GraphError(f"{path}: top-level value must be an object")
    return data


def milestones(data):
    out = data.get("milestones", [])
    return out if isinstance(out, list) else []


# ----------------------------------------------------------------- validate


def _is_str_list(value):
    return (
        isinstance(value, list)
        and bool(value)
        and all(isinstance(v, str) and v.strip() for v in value)
    )


def _sort_key(mid):
    match = re.match(r"^M([0-9]+)([a-z]?)$", mid)
    return (int(match.group(1)), match.group(2)) if match else (10**6, mid)


def _closure(start, by_id):
    """Every milestone reachable from `start`, following depends_on."""
    seen, stack = set(), [start]
    while stack:
        current = stack.pop()
        for dep in by_id.get(current, {}).get("depends_on", []):
            if dep not in seen:
                seen.add(dep)
                stack.append(dep)
    return seen


def validate(data, root=ROOT):
    """Return a list of human-readable error strings (empty means valid)."""
    errors = []

    if data.get("schema") != SCHEMA:
        errors.append(f"schema must be {SCHEMA!r}, found {data.get('schema')!r}")
    if not isinstance(data.get("updated"), str) or not data.get("updated"):
        errors.append("updated must be a date string")
    if not isinstance(data.get("version"), str) or not data.get("version"):
        errors.append("version must be a string")

    tracks = data.get("tracks")
    if not isinstance(tracks, dict) or not tracks:
        errors.append("tracks must be a non-empty object")
        tracks = {}
    for name, spec in tracks.items():
        if not isinstance(spec, dict):
            errors.append(f"track {name}: must be an object")
            continue
        for field in ("name", "objective"):
            if not isinstance(spec.get(field), str) or not spec.get(field, "").strip():
                errors.append(f"track {name}: {field} must be a non-empty string")
        allowed = spec.get("may_depend_on")
        if not isinstance(allowed, list) or not allowed:
            errors.append(f"track {name}: may_depend_on must be a non-empty list")
        else:
            for dep_track in allowed:
                if dep_track not in tracks:
                    errors.append(f"track {name}: may_depend_on names unknown track {dep_track!r}")

    roles = data.get("roles")
    if not _is_str_list(roles):
        errors.append("roles must be a non-empty list of strings")
        roles = []
    elif len(set(roles)) != len(roles):
        errors.append("roles contains duplicates")

    items = milestones(data)
    if not items:
        errors.append("milestones must be a non-empty list")
        return errors

    by_id = {}
    for index, m in enumerate(items):
        where = f"milestones[{index}]"
        if not isinstance(m, dict):
            errors.append(f"{where}: must be an object")
            continue
        mid = m.get("id")
        if not isinstance(mid, str) or not ID_RE.match(mid):
            errors.append(f"{where}: id must match M<number>[a-z], found {mid!r}")
            continue
        where = f"milestone {mid}"
        if mid in by_id:
            errors.append(f"{where}: duplicate id")
            continue
        by_id[mid] = m

        if m.get("track") not in tracks:
            errors.append(f"{where}: unknown track {m.get('track')!r}")
        if m.get("state") not in STATES:
            errors.append(f"{where}: state must be one of {', '.join(STATES)}; found {m.get('state')!r}")
        if m.get("owner_role") not in roles:
            errors.append(f"{where}: owner_role {m.get('owner_role')!r} is not in roles")
        if not isinstance(m.get("title"), str) or not m.get("title", "").strip():
            errors.append(f"{where}: title must be a non-empty string")

        deps = m.get("depends_on", [])
        if not isinstance(deps, list) or not all(isinstance(d, str) for d in deps):
            errors.append(f"{where}: depends_on must be a list of milestone ids")
            deps = []
        if len(set(deps)) != len(deps):
            errors.append(f"{where}: depends_on contains duplicates")
        if mid in deps:
            errors.append(f"{where}: depends on itself")

        for field in ("deliverables", "acceptance"):
            if not _is_str_list(m.get(field)):
                errors.append(f"{where}: {field} must be a non-empty list of non-empty strings")

        evidence = m.get("evidence", [])
        if not isinstance(evidence, list) or not all(isinstance(e, str) for e in evidence):
            errors.append(f"{where}: evidence must be a list of repository paths")
            evidence = []
        for path in evidence:
            if not os.path.exists(os.path.join(root, path)):
                errors.append(f"{where}: evidence path does not exist: {path}")

        if m.get("state") == "complete" and not evidence:
            errors.append(f"{where}: state is complete but no evidence is cited")
        if m.get("state") == "blocked":
            blocker = m.get("blocker")
            if not isinstance(blocker, str) or not blocker.strip():
                errors.append(f"{where}: state is blocked but no blocker is named")
        if m.get("state") in ("blocked", "not_started") and evidence:
            # Not an error: research milestones can cite standing documents.
            pass

        if "legacy" in m and not _is_str_list(m.get("legacy")):
            errors.append(f"{where}: legacy must be a list of strings when present")

    # Dangling dependencies, after every id is known.
    for mid, m in by_id.items():
        for dep in m.get("depends_on", []) or []:
            if dep not in by_id:
                errors.append(f"milestone {mid}: depends on unknown milestone {dep!r}")

    # Cycles: Kahn's algorithm over known ids only.
    indegree = {mid: 0 for mid in by_id}
    for mid, m in by_id.items():
        for dep in m.get("depends_on", []) or []:
            if dep in by_id:
                indegree[mid] += 1
    ready = [mid for mid, deg in indegree.items() if deg == 0]
    seen = 0
    while ready:
        current = ready.pop()
        seen += 1
        for mid, m in by_id.items():
            if current in (m.get("depends_on") or []):
                indegree[mid] -= 1
                if indegree[mid] == 0:
                    ready.append(mid)
    if seen != len(by_id):
        stuck = sorted((mid for mid, deg in indegree.items() if deg > 0), key=_sort_key)
        errors.append(f"dependency cycle among: {', '.join(stuck)}")

    # The architectural gate: no Track A milestone may sit behind Track B work.
    if seen == len(by_id) and not any("unknown milestone" in e for e in errors):
        for mid, m in sorted(by_id.items(), key=lambda kv: _sort_key(kv[0])):
            if m.get("track") != "A":
                continue
            for dep in sorted(_closure(mid, by_id), key=_sort_key):
                if by_id[dep].get("track") == "B":
                    errors.append(
                        f"track gate violated: Track A milestone {mid} depends on Track B milestone {dep}"
                    )

    return errors


# ------------------------------------------------------------------ queries


def roots(data):
    return [m for m in milestones(data) if not m.get("depends_on")]


def critical_path(data):
    """Longest dependency chain inside Track A (deterministic tie-break)."""
    by_id = {m["id"]: m for m in milestones(data) if isinstance(m, dict) and "id" in m}
    best = {}

    def longest(mid, stack=()):
        if mid in best:
            return best[mid]
        if mid in stack:  # cycle; validate() reports it
            return ([], 0)
        deps = [d for d in by_id[mid].get("depends_on", []) if d in by_id]
        if not deps:
            best[mid] = ([mid], 1)
            return best[mid]
        candidates = []
        for dep in deps:
            path, length = longest(dep, stack + (mid,))
            if path:
                candidates.append((path + [mid], length + 1))
        if not candidates:
            best[mid] = ([mid], 1)
        else:
            candidates.sort(key=lambda item: (-item[1], item[0]))
            best[mid] = candidates[0]
        return best[mid]

    track_a = [
        m["id"]
        for m in milestones(data)
        if isinstance(m, dict) and m.get("id") in by_id and m.get("track") == "A"
    ]
    if not track_a:
        return []
    paths = [longest(mid)[0] for mid in track_a]
    paths.sort(key=lambda p: (-len(p), p))
    return paths[0]


# ------------------------------------------------------------------- render


def render(data):
    lines = [
        f"PC5 ROADMAP  version {data.get('version', '?')}  schema {data.get('schema', '?')}  updated {data.get('updated', '?')}",
        "",
    ]
    for track_key in sorted(data.get("tracks", {})):
        spec = data["tracks"][track_key]
        suffix = "" if track_key == "A" else "  (never gates Track A)"
        lines.append(f"Track {track_key} — {spec.get('name', '?')}{suffix}")
        members = sorted(
            (m for m in milestones(data) if m.get("track") == track_key),
            key=lambda m: _sort_key(m.get("id", "")),
        )
        if not members:
            lines.append("  (no milestones)")
        for m in members:
            deps = m.get("depends_on") or []
            dep_text = ", ".join(sorted(deps, key=_sort_key)) if deps else "—"
            lines.append(f"  {m['id']:<5} {m['state']:<12} {m.get('title', '')}")
            lines.append(f"        depends on  {dep_text}")
        lines.append("")

    path = critical_path(data)
    lines.append("Track A critical path: " + (" -> ".join(path) if path else "(none)"))
    track_b = sorted(
        (m["id"] for m in milestones(data) if m.get("track") == "B"),
        key=_sort_key,
    )
    lines.append(
        "Track B milestones: " + (", ".join(track_b) if track_b else "(none)")
        + "  — every one of them may stop without changing a Track A release."
    )
    return "\n".join(lines) + "\n"


def sync_doc(doc_path=DEFAULT_DOC, rendered=None, data=None):
    """Replace the generated block. Returns True when the file changed."""
    if rendered is None:
        rendered = render(data if data is not None else load())
    with open(doc_path, "r", encoding="utf-8") as fh:
        text = fh.read()
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0 or end < 0 or end < start:
        raise GraphError(f"{doc_path}: generated block markers not found")
    block = f"{BEGIN}\n```\n{rendered.rstrip()}\n```\n{END}"
    updated = text[:start] + block + text[end + len(END):]
    if updated == text:
        return False
    with open(doc_path, "w", encoding="utf-8") as fh:
        fh.write(updated)
    return True


def doc_block(doc_path=DEFAULT_DOC):
    with open(doc_path, "r", encoding="utf-8") as fh:
        text = fh.read()
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < 0:
        raise GraphError(f"{doc_path}: generated block markers not found")
    body = text[start + len(BEGIN):end]
    lines = body.splitlines()
    while lines and not lines[0].strip():
        lines.pop(0)
    if lines and lines[0].strip() == "```":
        lines.pop(0)
    while lines and lines[-1].strip() in ("", "```"):
        lines.pop()
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------- cli


def main(argv=None):
    parser = argparse.ArgumentParser(description="Validate and render the PC5 milestone graph.")
    parser.add_argument("command", choices=("check", "render", "sync", "path"))
    parser.add_argument("--graph", default=DEFAULT_GRAPH)
    parser.add_argument("--doc", default=DEFAULT_DOC)
    args = parser.parse_args(argv)

    try:
        data = load(args.graph)
        errors = validate(data)
        if errors:
            for error in errors:
                print(f"roadmap: ERROR {error}", file=sys.stderr)
            print(f"roadmap: {len(errors)} error(s)", file=sys.stderr)
            return 1

        if args.command == "check":
            if not os.path.exists(args.doc):
                print(f"roadmap: ERROR document not found: {args.doc}", file=sys.stderr)
                return 1
            if doc_block(args.doc) != render(data):
                print(
                    "roadmap: ERROR generated block is out of date "
                    "(run: python3 tools/roadmap.py sync)",
                    file=sys.stderr,
                )
                return 1
            print(
                f"roadmap: OK — {len(milestones(data))} milestones, "
                f"tracks A/B separated, document in sync"
            )
            return 0

        if args.command == "render":
            sys.stdout.write(render(data))
            return 0

        if args.command == "path":
            print(" -> ".join(critical_path(data)))
            return 0

        changed = sync_doc(args.doc, render(data), data)
        print(f"roadmap: {'updated' if changed else 'already current'} {args.doc}")
        return 0
    except GraphError as exc:
        print(f"roadmap: ERROR {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
